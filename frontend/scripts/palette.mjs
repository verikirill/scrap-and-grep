// One palette for the web app and the video renderer, from one seed colour.
//   npx tsx scripts/palette.mjs
// Writes src/styles/palette.css (light and dark Material 3 roles as CSS
// variables) and ../shorts/src/palette.ts (the dark roles the videos use).
// Material's vibrant scheme keeps the brand blue vivid in the dark theme; amber
// and green are harmonised towards it so that warnings and successes belong to
// the same set. The light theme is built from its own palettes (see LIGHT).
import { writeFileSync } from 'node:fs'
import {
  Blend,
  DynamicScheme,
  Hct,
  MaterialDynamicColors,
  SchemeVibrant,
  TonalPalette,
  Variant,
  argbFromHex,
  hexFromArgb,
} from '@material/material-color-utilities'

const SEED = '#2f5bea'
const CUSTOM = { spark: '#f2a20c', success: '#2e7d32' }
// Colours a reader picks for a profile: tag-<name> is the tile, on-tag-<name>
// the icon on it. Harmonised towards the seed, so they sit in the same set.
const TAGS = {
  blue: '#2f5bea',
  violet: '#7c4dff',
  teal: '#00897b',
  green: '#2e7d32',
  amber: '#f2a20c',
  orange: '#ef6c00',
  red: '#d32f2f',
  pink: '#d81b60',
  slate: '#546e7a',
}
const ROLES = [
  'primary',
  'onPrimary',
  'primaryContainer',
  'onPrimaryContainer',
  'secondary',
  'onSecondary',
  'secondaryContainer',
  'onSecondaryContainer',
  'tertiary',
  'onTertiary',
  'tertiaryContainer',
  'onTertiaryContainer',
  'error',
  'onError',
  'errorContainer',
  'onErrorContainer',
  'surface',
  'onSurface',
  'surfaceVariant',
  'onSurfaceVariant',
  'surfaceContainerLowest',
  'surfaceContainerLow',
  'surfaceContainer',
  'surfaceContainerHigh',
  'surfaceContainerHighest',
  'surfaceBright',
  'surfaceDim',
  'outline',
  'outlineVariant',
  'inverseSurface',
  'inverseOnSurface',
  'inversePrimary',
  'scrim',
]

const kebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)
const seed = argbFromHex(SEED)
const seedHct = Hct.fromInt(seed)

// The light theme: slate. The seed blue sits at hue 276 in HCT, on the edge of
// violet, so neutrals derived from it (as the vibrant scheme does) tint every
// surface lilac. Here the neutrals lean the other way, towards cyan, and the
// blue is a little calmer than vibrant's electric #004bef.
const LIGHT = {
  primary: TonalPalette.fromHueAndChroma(seedHct.hue, 66),
  secondary: TonalPalette.fromHueAndChroma(seedHct.hue - 20, 16),
  tertiary: TonalPalette.fromHueAndChroma(seedHct.hue - 60, 24),
  neutral: TonalPalette.fromHueAndChroma(seedHct.hue - 25, 5),
  neutralVariant: TonalPalette.fromHueAndChroma(seedHct.hue - 25, 9),
}

function schemeFor(isDark) {
  if (isDark) return new SchemeVibrant(seedHct, true, 0)
  return new DynamicScheme({
    sourceColorHct: seedHct,
    variant: Variant.TONAL_SPOT,
    contrastLevel: 0,
    isDark: false,
    primaryPalette: LIGHT.primary,
    secondaryPalette: LIGHT.secondary,
    tertiaryPalette: LIGHT.tertiary,
    neutralPalette: LIGHT.neutral,
    neutralVariantPalette: LIGHT.neutralVariant,
  })
}

function roles(isDark) {
  const scheme = schemeFor(isDark)
  const out = Object.fromEntries(
    ROLES.map((role) => [kebab(role), hexFromArgb(MaterialDynamicColors[role].getArgb(scheme))]),
  )
  // Custom colours follow Material's custom-colour tones: 40/100/90/10 in
  // light, 80/20/30/90 in dark.
  for (const [name, hex] of Object.entries(CUSTOM)) {
    const palette = TonalPalette.fromInt(Blend.harmonize(argbFromHex(hex), seed))
    const [color, on, container, onContainer] = isDark ? [80, 20, 30, 90] : [40, 100, 90, 10]
    out[name] = hexFromArgb(palette.tone(color))
    out[`on-${name}`] = hexFromArgb(palette.tone(on))
    out[`${name}-container`] = hexFromArgb(palette.tone(container))
    out[`on-${name}-container`] = hexFromArgb(palette.tone(onContainer))
  }
  for (const [name, hex] of Object.entries(TAGS)) {
    const palette = TonalPalette.fromInt(Blend.harmonize(argbFromHex(hex), seed))
    const [tile, icon, swatch] = isDark ? [30, 90, 70] : [90, 30, 55]
    out[`tag-${name}`] = hexFromArgb(palette.tone(tile))
    out[`on-tag-${name}`] = hexFromArgb(palette.tone(icon))
    // The colour as a dot in the picker: strong enough to tell nine apart.
    out[`swatch-${name}`] = hexFromArgb(palette.tone(swatch))
  }
  return out
}

const light = roles(false)
const dark = roles(true)
const block = (values) =>
  Object.entries(values)
    .map(([name, hex]) => `  --md-${name}: ${hex};`)
    .join('\n')

writeFileSync(
  new URL('../src/styles/palette.css', import.meta.url),
  `/* Generated by scripts/palette.mjs from ${SEED}; do not edit by hand. */\n` +
    `:root {\n${block(light)}\n}\n\n.dark {\n${block(dark)}\n}\n`,
)

const shortsRoles = Object.fromEntries(
  Object.entries(dark).map(([name, hex]) => [
    name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase()),
    hex,
  ]),
)
writeFileSync(
  new URL('../../shorts/src/palette.ts', import.meta.url),
  `// Generated by frontend/scripts/palette.mjs from ${SEED}; do not edit by hand.\n` +
    `// The dark Material 3 roles of the web app, so videos and the site share colours.\n` +
    `export const PALETTE = ${JSON.stringify(shortsRoles, null, 2)} as const\n`,
)
console.log(`palette from ${SEED}: primary ${light.primary} / ${dark.primary}`)
